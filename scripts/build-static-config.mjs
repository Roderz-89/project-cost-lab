#!/usr/bin/env node
// Project Cost Lab — writes the assets-only routing/header config (no Worker script runs).
// Usage: node scripts/build-static-config.mjs   (also run at the end of build-news.mjs)
//   _redirects : one single-hop 301 for every non-canonical variant of every page
//                (/x.html, /x/, /x/index, /x/index.html; /index.html -> /; /guides -> /guides/;
//                /news/page/1 -> /news). Listing them explicitly beats html_handling's 307s.
//   _headers   : security headers, cache header and a fixed hash-based CSP on every response.
// www -> apex and http -> https are NOT here: they live in a Cloudflare dashboard Single Redirect
// rule + Always Use HTTPS (domain-level redirects are not supported in _redirects).
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SKIP = new Set([".git", "node_modules", ".wrangler", "content", "scripts"]);
const walk = (d) => readdirSync(join(ROOT, d)).flatMap((f) => {
  const p = d ? `${d}/${f}` : f;
  if (SKIP.has(f)) return [];
  return statSync(join(ROOT, p)).isDirectory() ? walk(p) : p.endsWith(".html") ? [p] : [];
});
const sha = (s) => "sha256-" + createHash("sha256").update(s, "utf8").digest("base64");

// Old URL -> new canonical URL (each target must be a live page; keep single hop).
export const EXTRA = [];

export const canonicalOf = (f) => (f === "index.html" ? "/" : f.endsWith("/index.html") ? "/" + f.slice(0, -"index.html".length) : "/" + f.slice(0, -5));

// Computed on call (not at import) so build-news.mjs sees the pages it has just written.
export function generate() {
  // ---- canonical URL for each HTML file -------------------------------------------------
  const pages = walk("").filter((f) => f !== "404.html").sort();

  // ---- _redirects -------------------------------------------------------------------------
  const rules = [];
  const add = (from, to) => { if (from !== to && !rules.some(([f]) => f === from)) rules.push([from, to]); };
  for (const f of pages) {
    const c = canonicalOf(f);
    if (c === "/") { add("/index", "/"); add("/index.html", "/"); continue; }
    if (c.endsWith("/")) { const b = c.slice(0, -1); add(b, c); add(b + ".html", c); add(c + "index", c); add(c + "index.html", c); continue; }
    add(c + ".html", c); add(c + "/", c); add(c + "/index", c); add(c + "/index.html", c);
  }
  // hand-made permanent moves, e.g. a guide turned into a news post: ["/guides/old", "/news/new"]
  for (const [from, to] of EXTRA) add(from, to);
  // page 1 of the news list is /news itself
  for (const v of ["/news/page/1", "/news/page/1/", "/news/page/1.html", "/news/page/1/index", "/news/page/1/index.html"]) add(v, "/news");
  const redirectsTxt = `# Generated by scripts/build-static-config.mjs — do not edit by hand.
# Single-hop 301s to the canonical apex path. www/http -> https://projectcostlab.co.uk is a
# Cloudflare dashboard Single Redirect rule (domain-level redirects are not supported here).
${rules.map(([f, t]) => `${f} ${t} 301`).join("\n")}
`;

  // ---- CSP: fixed policy; hashes for every inline script / inline handler ------------------
  const inline = new Set();
  for (const f of [...pages, "404.html"]) {
    const html = readFileSync(join(ROOT, f), "utf8");
    for (const m of html.matchAll(/<script(?![^>]*\bsrc=)(?![^>]*application\/ld\+json)[^>]*>([\s\S]*?)<\/script>/g)) inline.add(sha(m[1]));
    for (const m of html.matchAll(/\son(?:click|load|change|input|submit)="([^"]*)"/g)) inline.add(sha(m[1].replace(/&quot;/g, '"').replace(/&amp;/g, "&")));
  }
  const scriptHashes = [...inline].sort();
  const CSP = [
    "default-src 'self'",
    `script-src 'self' 'unsafe-hashes' ${scriptHashes.map((h) => `'${h}'`).join(" ")}`,
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data:",
    "font-src 'self'",
    "connect-src 'self'",
    "frame-src 'self'",
    "worker-src 'self' blob:",
    "frame-ancestors 'self'",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "upgrade-insecure-requests",
  ].join("; ");
  const headersTxt = `# Generated by scripts/build-static-config.mjs — do not edit by hand.
/*
  Cache-Control: public, max-age=0, must-revalidate
  Strict-Transport-Security: max-age=31536000
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=()
  X-Frame-Options: SAMEORIGIN
  Content-Security-Policy: ${CSP}

# The 404 template is only meant to be served with status 404; keep a direct hit out of the index.
/404
  X-Robots-Tag: noindex
/404.html
  X-Robots-Tag: noindex
`;
  // CSP-nonce Worker: runs first ONLY on the canonical page paths (exact matches, no globs), so
  // redirect sources, 404s, css/js/fonts/images, robots.txt, sitemap.xml, ads.txt, the IndexNow key
  // and BingSiteAuth.xml are all served by static assets without invoking it.
  // News grows ~3 posts/week, so it uses one glob (+ negations for its redirect sources) to stay
  // well under run_worker_first's 100-entry limit. Negations take precedence over positives.
  const workerPaths = [
    ...[...new Set(pages.map(canonicalOf))].filter((c) => !c.startsWith("/news/")).sort(),
    "/news/*", "!/news/", "!/news/index", "!/news/*.html", "!/news/*/", "!/news/*/index", "!/news/*/index.html", "!/news/page/1",
  ];
  const cspMjs = `// Generated by scripts/build-static-config.mjs — do not edit by hand.\nexport const CSP = ${JSON.stringify(CSP)};\n`;
  const wranglerTxt = `{
  "name": "projectcostlab",
  "compatibility_date": "2026-09-22",
  // Generated by scripts/build-static-config.mjs — do not edit by hand.
  // Static assets serve everything; _redirects + _headers + 404.html do routing and headers.
  // worker.js runs first ONLY on the canonical HTML page paths listed in run_worker_first, to replace
  // the CSP with the fixed policy + a per-request 'nonce-…' (lets Cloudflare's injected JS
  // Detections script run). www -> apex and http -> https are a dashboard Single Redirect rule.
  "main": "worker.js",
  "assets": {
    "directory": ".",
    "binding": "ASSETS",
    "html_handling": "auto-trailing-slash",
    "not_found_handling": "404-page",
    "run_worker_first": ${JSON.stringify(workerPaths)}
  },
  "workers_dev": false
}
`;
  return { pages, redirects: rules, scriptHashes, csp: CSP, workerPaths, files: { _redirects: redirectsTxt, _headers: headersTxt, "csp.mjs": cspMjs, "wrangler.jsonc": wranglerTxt } };
}

export function writeStaticConfig() {
  const g = generate();
  for (const [f, s] of Object.entries(g.files)) writeFileSync(join(ROOT, f), s);
  console.log(`Static config OK: _redirects ${g.redirects.length} rules (all 301, single hop); _headers CSP with ${g.scriptHashes.length} script hash(es); worker on ${g.workerPaths.length} page paths.`);
  return g;
}

if (fileURLToPath(import.meta.url) === process.argv[1]) writeStaticConfig();
